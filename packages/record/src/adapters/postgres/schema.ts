import {
  date,
  doublePrecision,
  index,
  integer,
  jsonb,
  pgSchema,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';
import type { Measurements } from '../../domain/stone.ts';

// The Record context's own Postgres schema (ADR 0005). Change it, then run
// `pnpm --filter @varda/record db:generate` and commit the new migration.
export const record = pgSchema('record');

/** A lap as stored in `stones.laps`: its start as an ISO instant. */
export type StoredLap = {
  start: string;
  elapsedTime: number;
  movingTime: number;
  distance: number | null;
  trigger: 'manual' | 'distance' | 'time' | 'other';
};

export const stones = record.table(
  'stones',
  {
    // UUIDv7 from the ids adapter, never generated by the database (ADR 0006).
    id: uuid('id').primaryKey(),
    // The athlete's person ID, by identity only: no foreign key across schemas (ADR 0005).
    athlete: uuid('athlete').notNull(),
    sessionKey: text('session_key').notNull(),
    fileName: text('file_name').notNull(),
    start: timestamp('start', { withTimezone: true }).notNull(),
    // Seconds the local time was ahead of UTC; 0 for stones placed before it was kept, as UTC.
    localOffset: integer('local_offset').notNull().default(0),
    localDate: date('local_date', { mode: 'string' }).notNull(),
    sport: text('sport').notNull(),
    // Metres, or null when the watch recorded none.
    distance: doublePrecision('distance'),
    // Seconds.
    movingTime: doublePrecision('moving_time').notNull(),
    elapsedTime: doublePrecision('elapsed_time').notNull(),
    laps: jsonb('laps').$type<StoredLap[]>().notNull(),
    // `[lat, lon]` pairs in degrees, or null when the watch recorded no GPS.
    trace: jsonb('trace').$type<[number, number][]>(),
    // 1–10, or null when the athlete gave the watch no rating.
    effort: integer('effort'),
    // `{ manufacturer, model }` of the watch that recorded it, or null.
    device: jsonb('device').$type<{ manufacturer: string; model: string | null }>(),
    // Garmin's training load and Training Effect, as reference only (ADR 0003); never answered. Or null.
    garminReference: jsonb('garmin_reference').$type<{
      trainingLoad: number | null;
      aerobicTrainingEffect: number | null;
      anaerobicTrainingEffect: number | null;
    }>(),
    // The athlete's measurements the watch had (kg, m, bpm), or null when it had none.
    measurements: jsonb('measurements').$type<Measurements>(),
  },
  (table) => [
    // A session is placed as a stone only once (Record glossary).
    unique('stones_athlete_session_key_unique').on(table.athlete, table.sessionKey),
    // Serves `Stones.ofAthlete`.
    index('stones_athlete_local_date_index').on(table.athlete, table.localDate),
  ],
);
